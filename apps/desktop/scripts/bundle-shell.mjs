#!/usr/bin/env node
/**
 * esbuild 打包 Electron 壳代码（ADR-0008 D2 / D15）。
 *
 * 用法（在 F:\new1.2 执行）：
 *     node apps/desktop/scripts/bundle-shell.mjs
 *
 * 入口 → 产物：
 *     apps/desktop/src/main.ts     → apps/desktop/dist/main.cjs      （package.json 的 "main" 逐字指向）
 *     apps/desktop/src/preload.ts  → apps/desktop/dist/preload.cjs
 *
 * 冻结参数：
 *     platform: 'node', format: 'cjs', target: 'node22', bundle: true, sourcemap: false
 *
 * external 策略（与 shell-eng 逐字约定）：
 *     external 只允许 'electron'，其余全部内联。
 *     理由：electron-builder 的 files 清单排除了 node_modules 通配（见
 *     apps/desktop/electron-builder.yml 的 files 段），asar 内不会有
 *     node_modules 供运行期 require ⇒ 非 electron 的依赖必须内联。
 *     注：apps/desktop/src/updater/zip.ts 用 node:zlib 自实现 ZIP 读取器，
 *     全仓无 yauzl 导入 ⇒ 无 yauzl 可内联（原注释的「含 yauzl」已过时）。
 *
 * ⚠️ 本注释块内不得出现「星号 + 斜杠」的连续两字符（例如在正文里直接写
 *    glob 通配），否则会提前终止块注释并导致本文件语法错误。需要书写
 *    glob 时请用文字描述或拼接字符串。
 *
 * 注意：源码内一律用 './foo.js' 形式的相对 import（仓库既有风格）；
 * esbuild 在 bundle TS 时会把 '.js' 说明符回退解析到 '.ts'，不得禁用该行为
 * （不要加 `--external:./*`、不要设 `resolveExtensions` 为不含 .ts 的值）。
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DESKTOP = path.resolve(__dirname, '..');
const REPO = path.resolve(DESKTOP, '..', '..');
const SRC = path.join(DESKTOP, 'src');
const OUT = path.join(DESKTOP, 'dist');

const log = (...a) => console.log('[bundle-shell]', ...a);

// esbuild 从仓库根 node_modules 解析（apps/desktop 的 devDependencies 里有精确版本，
// 但 pnpm hoisted 模式下根 node_modules/esbuild 是同一个实体）
const require = createRequire(path.join(REPO, 'package.json'));
let esbuild;
try {
  esbuild = require('esbuild');
} catch {
  esbuild = require(path.join(DESKTOP, 'node_modules', 'esbuild'));
}

const ENTRIES = [
  { in: path.join(SRC, 'main.ts'), out: path.join(OUT, 'main.cjs') },
  { in: path.join(SRC, 'preload.ts'), out: path.join(OUT, 'preload.cjs') },
];

async function main() {
  const missing = ENTRIES.filter((e) => !fs.existsSync(e.in)).map((e) => e.in);
  if (missing.length) {
    throw new Error(
      '缺少入口文件（apps/desktop/src/** 由 shell-eng 拥有，尚未就绪）：\n  ' + missing.join('\n  '),
    );
  }

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  for (const e of ENTRIES) {
    await esbuild.build({
      entryPoints: [e.in],
      outfile: e.out,
      platform: 'node',
      format: 'cjs',
      target: 'node22',
      bundle: true,
      sourcemap: false,
      // external 只允许 electron（见文件头说明）
      external: ['electron'],
      // 让 esbuild 读 tsconfig（ES2022 / strict / 模块解析风格）
      tsconfig: path.join(DESKTOP, 'tsconfig.json'),
      logLevel: 'info',
      banner: {
        js: '/* NovelMuse desktop shell — generated by apps/desktop/scripts/bundle-shell.mjs. DO NOT EDIT. */',
      },
    });
    const size = fs.statSync(e.out).size;
    log(`✔ ${path.relative(REPO, e.in)} → ${path.relative(REPO, e.out)}  ${size} B`);
  }

  // 自检：main.cjs 必须存在（package.json 的 "main" 指向它）
  const mainCjs = path.join(OUT, 'main.cjs');
  if (!fs.existsSync(mainCjs)) throw new Error('dist/main.cjs 未产出');
  log('OK');
}

main().catch((err) => {
  console.error('[bundle-shell] 失败:', err?.message ?? err);
  process.exit(1);
});